def replace_table_after(s, caption, new_tbl):
    i = s.index(caption)
    a = s.index("<w:tbl>", i)
    b = s.index("</w:tbl>", a) + len("</w:tbl>")
    return s[:a] + new_tbl + s[b:]


LIST_PPR = ('<w:pPr><w:tabs><w:tab w:val="left" w:pos="709"/></w:tabs><w:spacing w:after="0" w:before="0" '
            'w:line="360" w:lineRule="auto"/><w:ind w:left="709" w:hanging="709"/><w:jc w:val="both"/></w:pPr>')


def para_with_lines(s, marker):
    """Абзац со списком (строки через \\n) -> отдельные абзацы с тем же оформлением."""
    i = s.index(marker)
    a = max(s.rfind("<w:p>", 0, i), s.rfind("<w:p ", 0, i))
    b = s.index("</w:p>", i) + len("</w:p>")
    p = s[a:b]
    text = re.search(r'<w:t xml:space="preserve">(.*?)</w:t>', p, re.S).group(1)
    parts = text.split("\n")
    li = re.sub(r"<w:pPr>.*?</w:pPr>", LIST_PPR, p, count=1, flags=re.S)
    out = p.replace(text, parts[0]) + "".join(li.replace(text, "–\t" + x[2:]) for x in parts[1:])
    return s[:a] + out + s[b:]


