RPR = ('<w:rPr><w:rFonts w:ascii="Times New Roman" w:cs="Times New Roman" w:eastAsia="Times New Roman" '
       'w:hAnsi="Times New Roman"/><w:sz w:val="20"/><w:szCs w:val="20"/></w:rPr>')
MAR = ('<w:tcMar><w:top w:type="dxa" w:w="40"/><w:left w:type="dxa" w:w="80"/><w:bottom w:type="dxa" w:w="40"/>'
       '<w:right w:type="dxa" w:w="80"/></w:tcMar>')


def cell(text, w, jc="left", vmerge=None):
    vm = "" if vmerge is None else ('<w:vMerge w:val="restart"/>' if vmerge == "restart" else "<w:vMerge/>")
    run = f'<w:r>{RPR}<w:t xml:space="preserve">{escape(text, quote=False)}</w:t></w:r>' if text else ""
    return (f'<w:tc><w:tcPr><w:tcW w:type="dxa" w:w="{w}"/>{vm}{MAR}<w:vAlign w:val="center"/></w:tcPr>'
            f'<w:p><w:pPr><w:keepNext w:val="false"/><w:keepLines/><w:spacing w:after="0" w:before="0" w:line="240"/>'
            f'<w:jc w:val="{jc}"/></w:pPr>{run}</w:p></w:tc>')


def row(cells, header=False):
    hdr = "<w:tblHeader/>" if header else '<w:tblHeader w:val="false"/>'
    return (f'<w:tr><w:trPr><w:cantSplit/>{hdr}<w:trHeight w:val="454" w:hRule="atLeast"/></w:trPr>'
            + "".join(cells) + "</w:tr>")


def table(widths, head, rows):
    grid = "".join(f'<w:gridCol w:w="{w}"/>' for w in widths)
    out = ('<w:tbl><w:tblPr><w:tblW w:type="dxa" w:w="9638"/><w:jc w:val="center"/><w:tblBorders>'
           '<w:top w:val="single" w:color="000000" w:sz="4"/><w:left w:val="single" w:color="000000" w:sz="4"/>'
           '<w:bottom w:val="single" w:color="000000" w:sz="4"/><w:right w:val="single" w:color="000000" w:sz="4"/>'
           '<w:insideH w:val="single" w:color="000000" w:sz="4"/><w:insideV w:val="single" w:color="000000" w:sz="4"/>'
           f'</w:tblBorders></w:tblPr><w:tblGrid>{grid}</w:tblGrid>')
    out += row([cell(h, w, "center") for h, w in zip(head, widths)], header=True)
    for r in rows:
        out += row([cell(t, w, vmerge=vm) for (t, vm), w in zip(r, widths)])
    return out + "</w:tbl>"


